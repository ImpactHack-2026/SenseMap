import type { EvidenceItem, HourlyEstimate, IntensityLevel, Restaurant, SensoryProfile } from '../types'

/**
 * Fictional Fremont restaurants used when Google Places is not connected.
 * Structurally identical to what the Google provider returns, so the UI
 * never has to know which source it is rendering.
 */

const LEVEL: Record<string, IntensityLevel> = { L: 'low', M: 'moderate', H: 'high' }

/** Pattern covers 8 AM through 9 PM, one character per hour. */
function curve(pattern: string): HourlyEstimate[] {
  return pattern.split('').map((c, i) => ({ hour: 8 + i, level: LEVEL[c] }))
}

function ev(
  id: string,
  factor: EvidenceItem['factor'],
  statement: string,
  mentions: number,
  excerpts: string[],
): EvidenceItem {
  return {
    id,
    factor,
    statement,
    mentions,
    excerpts: excerpts.map((text) => ({ text, kind: 'illustrative' })),
  }
}

const ANALYZED_AT = '2026-03-01T00:00:00.000Z'

function sensory(p: Omit<SensoryProfile, 'method' | 'analyzedAt'>): SensoryProfile {
  return { ...p, method: 'demo-curated', analyzedAt: ANALYZED_AT }
}

